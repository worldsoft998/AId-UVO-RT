"""Launching and supervising simulator runs (the blackbox control loop).

Responsibilities:

* build the ``vsim`` command line for one run (seed + knob plusargs);
* generate a *simulator-only* do-file that bounds the run and saves coverage;
* stream the transcript, and abort a run early when it is clearly wasting time;
* collect the artifacts (transcript, UCDB) for the coverage importer.

The generated do-file contains nothing but simulator commands -- no design
knowledge, no testbench hooks, no source edits.
"""

from __future__ import annotations

import os
import signal
import subprocess
import time
from dataclasses import dataclass, field
from typing import Any, Callable, Dict, List, Optional

from aiduvo.blackbox.logwatch import TranscriptSummary, TranscriptWatcher
from aiduvo.srie.launcher import SimLaunch, find_executable


@dataclass
class RunArtifacts:
    returncode: int = 0
    wall_s: float = 0.0
    log_path: str = ""
    ucdb_path: str = ""
    aborted: bool = False
    timed_out: bool = False
    error: str = ""
    summary: TranscriptSummary = field(default_factory=TranscriptSummary)
    argv: List[str] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "returncode": self.returncode, "wall_s": self.wall_s, "log_path": self.log_path,
            "ucdb_path": self.ucdb_path, "aborted": self.aborted, "timed_out": self.timed_out,
            "error": self.error, "summary": self.summary.to_dict(), "argv": self.argv,
        }


def write_run_do(
    path: str,
    run_time: str = "1000 us",
    ucdb: str = "",
    user_do: str = "",
    pre_lines: Optional[List[str]] = None,
    post_lines: Optional[List[str]] = None,
) -> str:
    """Generate the do-file that bounds one run and saves coverage."""
    lines = ["# generated by AId-UVO-RT -- simulator commands only"]
    lines += list(pre_lines or [])
    save = f"coverage save {ucdb}" if ucdb else ""
    if save:
        lines += ["onfinish {", f"    {save}", "    quit -f", "}"]
    if user_do:
        lines.append(f"do {user_do}")
    else:
        lines.append(f"run {run_time}")
    lines += list(post_lines or [])
    if save:
        lines.append(save)
    lines.append("quit -f")
    os.makedirs(os.path.dirname(os.path.abspath(path)) or ".", exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    return path


class SimRunner:
    """Runs one simulator invocation and watches it."""

    def __init__(
        self,
        launch: SimLaunch,
        log_path: str,
        ucdb_path: str = "",
        timeout_s: float = 3600.0,
        abort_on_error: bool = True,
        abort_on_assert: bool = False,
        stall_seconds: float = 0.0,
        poll_interval: float = 0.25,
        on_event: Optional[Callable[[Any], None]] = None,
    ):
        self.launch = launch
        self.log_path = log_path
        self.ucdb_path = ucdb_path
        self.timeout_s = timeout_s
        self.abort_on_error = abort_on_error
        self.abort_on_assert = abort_on_assert
        self.stall_seconds = stall_seconds
        self.poll_interval = poll_interval
        self.on_event = on_event

    def run(self) -> RunArtifacts:
        os.makedirs(os.path.dirname(os.path.abspath(self.log_path)) or ".", exist_ok=True)
        launch = self.launch
        if not os.path.isabs(launch.exe) and find_executable(launch.exe) is None:
            return RunArtifacts(error=f"simulator executable {launch.exe!r} not found", ucdb_path="")
        argv = launch.argv()
        env = {**os.environ, **launch.env}
        t0 = time.time()
        art = RunArtifacts(log_path=self.log_path, ucdb_path=self.ucdb_path, argv=argv)
        watcher = TranscriptWatcher(self.log_path)
        try:
            with open(self.log_path, "w", encoding="utf-8", errors="replace") as log:
                kwargs: Dict[str, Any] = dict(
                    stdout=log, stderr=subprocess.STDOUT, stdin=subprocess.DEVNULL,
                    cwd=launch.cwd or None, env=env,
                )
                if os.name == "nt":  # pragma: no cover - Windows only
                    kwargs["creationflags"] = subprocess.CREATE_NEW_PROCESS_GROUP
                else:
                    kwargs["start_new_session"] = True
                proc = subprocess.Popen(argv, **kwargs)  # type: ignore[arg-type]
                last_change = time.time()
                last_lines = 0
                while proc.poll() is None:
                    time.sleep(self.poll_interval)
                    for evt in watcher.poll():
                        if self.on_event:
                            self.on_event(evt)
                    if watcher.summary.lines != last_lines:
                        last_lines = watcher.summary.lines
                        last_change = time.time()
                    if watcher.should_abort(self.abort_on_error, self.abort_on_assert):
                        art.aborted = True
                        art.error = watcher.summary.first_error
                        self._interrupt(proc)
                        break
                    if self.stall_seconds > 0 and (time.time() - last_change) > self.stall_seconds:
                        art.aborted = True
                        art.error = f"no transcript activity for {self.stall_seconds}s"
                        self._interrupt(proc)
                        break
                    if (time.time() - t0) > self.timeout_s:
                        art.timed_out = True
                        art.error = f"run exceeded {self.timeout_s}s"
                        self._interrupt(proc)
                        break
                try:
                    art.returncode = proc.wait(timeout=60)
                except subprocess.TimeoutExpired:  # pragma: no cover
                    proc.kill()
                    art.returncode = proc.wait()
        except FileNotFoundError as exc:
            art.error = str(exc)
            art.returncode = -1
        watcher.poll()
        art.summary = watcher.summary
        art.wall_s = time.time() - t0
        if not art.error and watcher.summary.first_error:
            art.error = watcher.summary.first_error
        return art

    @staticmethod
    def _interrupt(proc: subprocess.Popen) -> None:
        """Ask the simulator to stop *gracefully* so it can still save coverage."""
        try:
            if os.name == "nt":  # pragma: no cover - Windows only
                proc.send_signal(signal.CTRL_BREAK_EVENT)
            else:
                proc.send_signal(signal.SIGINT)
        except (OSError, ValueError):  # pragma: no cover
            try:
                proc.terminate()
            except OSError:
                pass
